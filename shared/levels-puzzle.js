// 6번째 마을 '수수께끼 숲': 생각하는 협동 퍼즐. 친구마다 '다른 일'을 동시에 해야 풀림
//  🔭 망루: 망루에 선 친구 화면에만 안개 늪의 징검다리가 보임 → 말로 길 안내, 다른 친구들은 바구니 밀기
//  🔢 그림 암호 문: 표지판 오두막에 들어간 한 친구 화면에만 암호가 보이고, 그동안만 그림 발판이 눌림 → 읽어 주기 + 밟기
//  🚰 레버: 레버 위에 서 있는 동안만 다리가 놓이거나 센 물살이 멈춤 → 레버 친구는 못 밀어요
// 모둠 미션 6단계 + 짝 미션 6단계 (같은 퍼즐 장소, 바구니 무게·암호 길이로 난이도 맞춤)
import { vwall, gateV, code, lever, swamp, L } from './levelkit.js';
import { R } from './geometry.js';

function puzzleLevels(duo) {
  const w2 = duo ? 1 : 2;             // 짝은 한 명이 퍼즐을 맡으면 나머지 한 명이 혼자 밀 수 있게
  const len = (team) => (duo ? 3 : team);
  const P = (def) => ({ ...L({ world: 5, minPlayers: 2, ...def }), pumpkinHolds: [] });
  const suffix = duo ? ' 둘이서' : '';
  return [
    P({ name: `망루 길잡이${suffix}`,
      tip: '🔭 망루에 올라간 친구 눈에만 안개 늪의 징검다리가 보여요! 말로 길을 알려 주세요.',
      start: { x: 150, y: 160 }, crate: { x: 330, y: 160, weight: w2 },
      swamps: [swamp(480, 0, 880, 720, [[6, 1], [7, 1], [6, 2], [7, 2], [6, 3], [7, 3], [6, 4], [7, 4], [6, 5], [7, 5], [6, 6], [7, 6],
        [8, 5], [9, 5], [10, 5], [8, 6], [9, 6], [10, 6]])],
      lookouts: [{ x: 300, y: 580 }],
      berries: [[600, 520], [180, 620], [1000, 150]] }),
    P({ name: `그림 암호 문${suffix}`,
      tip: '🔢 오두막 문 앞 얼굴 발판을 먼저 밟은 친구 한 명만 오두막에 들어가 암호를 볼 수 있어요(들어가면 못 나와요). 그 친구가 읽어 주면 다른 친구가 그림 발판을 순서대로 밟아요!',
      crate: { x: 330, y: 360, weight: duo ? 3 : 2 },
      gateDefs: [gateV(900, 285, 435, code([180, 110], [[430, 600], [560, 600], [690, 600], [820, 600]], len(3)))],
      berries: [[180, 620], [620, 120], [1130, 620]] }),
    P({ name: `다리 레버${suffix}`,
      tip: '🚰 레버 위에 서 있는 동안만 다리가 놓여요. 레버 친구는 못 밀어요, 나머지 친구들이 바구니를 건너편으로!',
      crate: { x: 300, y: 360, weight: w2 },
      water: [R(600, 0, 720, 280), R(600, 440, 720, 720)],
      bridges: [R(600, 280, 720, 440)],
      levers: [lever(450, 120), lever(870, 600)],
      berries: [[660, 360], [450, 620], [1130, 140]] }),
    P({ name: `물살 멈추기${suffix}`,
      tip: '🚰 센 물살은 바구니도 떠내려 보내요! 아래 연못에 빠지면 바구니가 처음 자리로. 레버로 물살을 멈춰요.',
      crate: { x: 300, y: 300, weight: w2 },
      streams: [{ ...R(520, 0, 720, 600), vx: 0, vy: 170, strong: true, lever: true }],
      water: [R(520, 600, 720, 720)],
      levers: [lever(420, 600), lever(830, 120)],
      berries: [[620, 120], [620, 420], [1130, 620]] }),
    P({ name: `망루와 암호${suffix}`,
      tip: '먼저 그림 암호로 문을 열고, 그다음 망루에서 늪 길을 알려 줘요. 누가 무엇을 맡을까요?',
      crate: { x: 300, y: 360, weight: w2 }, home: { x: 1150, y: 360 },
      gateDefs: [gateV(520, 250, 400, code([140, 620], [[150, 110], [260, 110], [370, 110], [260, 210]], len(4), 'up'))],
      swamps: [swamp(640, 0, 960, 720, [[8, 1], [9, 1], [8, 2], [9, 2], [8, 3], [9, 3], [8, 4], [9, 4], [10, 1], [11, 1], [10, 2], [11, 2]])],
      lookouts: [{ x: 585, y: 620 }],
      berries: [[440, 620], [720, 280], [1150, 620]] }),
    P({ name: `수수께끼 숲 대작전${suffix}`,
      tip: '레버 다리 → 그림 암호 문 → 안개 늪! 모두 다른 일을 맡아야 해요.',
      start: { x: 120, y: 360 }, crate: { x: 250, y: 360, weight: w2 }, home: { x: 1150, y: 360 },
      water: [R(360, 0, 460, 280), R(360, 440, 460, 720)],
      bridges: [R(360, 280, 460, 440)],
      levers: [lever(250, 130), lever(600, 660)],
      gateDefs: [gateV(700, 285, 435, code([560, 90], [[505, 255], [615, 255], [510, 560], [610, 560]], len(4)))],
      swamps: [swamp(720, 0, 1040, 720, [[9, 3], [10, 3], [9, 4], [10, 4], [9, 5], [10, 5], [9, 6], [10, 6], [11, 5], [12, 5], [11, 6], [12, 6]])],
      lookouts: [{ x: 150, y: 600 }],
      berries: [[150, 120], [800, 520], [1150, 620]] })
  ];
}

export const PUZZLE_TEAM = puzzleLevels(false);
export const PUZZLE_DUO = puzzleLevels(true);
